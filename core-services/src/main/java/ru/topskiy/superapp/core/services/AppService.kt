package ru.topskiy.superapp.core.services

/**
 * Lifecycle-интерфейс для background-части сервиса.
 *
 * Сервис реализует [AppService] если ему нужна фоновая активность:
 * периодические проверки, синхронизация, слежение за данными и т.д.
 *
 * Управление жизненным циклом полностью на стороне [ServiceManager]:
 *   — [start] вызывается когда сервис включается (или при старте приложения)
 *   — [stop]  вызывается когда сервис отключается пользователем
 *
 * Реализация возвращается через [ServiceProvider.createService].
 */
interface AppService {

    /**
     * Запустить фоновую работу сервиса.
     * Вызывается единожды при активации. Может подписаться на потоки,
     * запустить периодические задачи и т.п.
     */
    suspend fun start()

    /**
     * Остановить фоновую работу сервиса.
     * Вызывается при отключении сервиса пользователем.
     * Должен отменить все подписки и освободить ресурсы.
     */
    suspend fun stop()
}
