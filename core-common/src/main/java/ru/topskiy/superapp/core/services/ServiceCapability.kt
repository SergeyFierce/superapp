package ru.topskiy.superapp.core.services

/**
 * Расширяемый набор возможностей сервиса.
 *
 * Добавление новой возможности — одна строка здесь + проверка
 * в нужном системном компоненте. Существующие сервисы не затрагиваются.
 */
enum class ServiceCapability {
    /** Сервис предоставляет блоки на экране "Главная" */
    HOME_BLOCK,

    /** Сервис участвует в глобальном поиске */
    SEARCH_PROVIDER,

    /** Сервис имеет background-часть ([AppService]) и управляется [ServiceManager] */
    BACKGROUND_SERVICE,

    /** Сервис поддерживает синхронизацию данных */
    SYNC,

    /** Сервис может отправлять системные уведомления */
    NOTIFICATIONS,

    /** Сервис обрабатывает deep link'и */
    DEEP_LINK,
}
